import { execSync } from "node:child_process";
import { mkdirSync, readFileSync, writeFileSync } from "node:fs";

// AWS counterpart of scripts/vercel-build.mjs. Prepares everything that
// `sst deploy` uploads: the static frontend (frontend/dist, served by the
// StaticSite) and the SPA template the Lambda bundles for /results/<id>.

// 0. DAZUBI-derived data; bundled into the function, never into static files
execSync("npm run data:build-dazubi", { stdio: "inherit" });

// 1. Frontend
execSync("npm run build --workspace=frontend", { stdio: "inherit" });

// 2. SPA shell for the server-rendered occupation preview and the
//    /results/* SPA routes (see backend/src/lambda.ts)
const spaIndexHtml = readFileSync("frontend/dist/index.html", "utf8");
mkdirSync("backend/src/generated", { recursive: true });
writeFileSync(
	"backend/src/generated/spaIndexTemplate.ts",
	`// Generated by scripts/aws-build.mjs - do not edit manually.\nexport const SPA_INDEX_HTML = ${JSON.stringify(spaIndexHtml)};\n`,
);
